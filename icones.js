/** Devolve o markup de um ícone. `rotulo` torna o ícone anunciável; sem ele,
 *  fica aria-hidden (caso em que o texto ao lado já descreve a ação). */
export function ic(nome, { classe = 'ic', rotulo = null } = {}) {
  const d = P[nome]
  if (!d) return ''
  const a11y = rotulo ? `role="img" aria-label="${rotulo}"` : 'aria-hidden="true"'
  return `<svg class="${classe}" viewBox="0 0 24 24" ${a11y}>${d}</svg>`
}

